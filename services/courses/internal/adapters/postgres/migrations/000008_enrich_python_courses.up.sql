## Как думать о типах данных

Значение определяет, какие операции имеют смысл. Например, числа можно складывать как числа, а строки — соединять как текст. Выражение 2 + 3 вычисляется в 5, но выражение "2" + "3" даёт строку "23". Python не превращает текст в число автоматически.

    value = input("Введите число: ")
    number = int(value)
    print(number * 2)

Если ожидается дробное значение, используйте float(). Преобразование завершится ошибкой, если строка не представляет допустимое число. В следующих темах вы научитесь проверять данные до выполнения вычислений.

