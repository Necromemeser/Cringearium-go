## Изменение и перебор коллекций

Список подходит для последовательности значений, порядок которых важен. Индексы начинаются с нуля, а индекс -1 обозначает последний элемент непустого списка. Функция len() сообщает количество элементов.

    tasks = ["прочитать", "решить", "проверить"]
    print(tasks[-1])
    tasks.append("повторить")

Метод append() изменяет существующий список и добавляет элемент в конец. Если нужно обработать каждый элемент, не обязательно обращаться к нему по индексу:

    for task in tasks:
        print("Задача:", task)

Словарь удобен для именованных характеристик объекта. Например, student["name"] возвращает значение по ключу name. Ключи должны быть уникальными; новое присваивание по уже существующему ключу заменит старое значение.

