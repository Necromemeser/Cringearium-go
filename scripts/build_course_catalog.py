#!/usr/bin/env python3
"""Compile authored course supplements into the immutable PostgreSQL v10 migration.
No network access. Run --check in CI to catch stale SQL or missing local assets.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'content/courses'
TARGET = ROOT / 'services/courses/internal/adapters/postgres/migrations/000010_course_enrichment.up.sql'
DOWN_TARGET = TARGET.with_name('000010_course_enrichment.down.sql')


def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def compile_catalog():
    for asset in json.loads((ROOT / 'frontend/public/images/memes/sources.json').read_text()):
        image = ROOT / 'frontend/public/images/memes' / asset['file']
        assert hashlib.sha256(image.read_bytes()).hexdigest() == asset['sha256'], f"Original image changed: {image}"
    catalog = json.loads((SOURCE / 'catalog.json').read_text())
    assert catalog['version'] == 1
    subjects = catalog['subjects']
    codes = {p['code'] for s in subjects for p in s['pages']}
    assert len(codes) == sum(len(s['pages']) for s in subjects)
    edges = {p['code']: p['prerequisites'] for s in subjects for p in s['pages']}
    def visit(code, trail):
        assert code not in trail, f'Prerequisite cycle: {code}'
        for dep in edges[code]:
            assert dep in codes and dep.split('.')[0] == code.split('.')[0]
            visit(dep, trail + [code])
    for code in codes:
        visit(code, [])
    sql = ['-- Generated by scripts/build_course_catalog.py; edit content/courses, then regenerate.',
           '-- Preserve all original pages, tests, attempts and assessment definitions.', 'BEGIN;',
           'CREATE TABLE course_upgrade_v10_original_pages (page_id BIGINT PRIMARY KEY REFERENCES course_pages(id) ON DELETE CASCADE, content TEXT, position INTEGER NOT NULL, updated_at TIMESTAMPTZ NOT NULL);',
           'CREATE TABLE course_upgrade_v10_added_pages (page_id BIGINT PRIMARY KEY REFERENCES course_pages(id) ON DELETE CASCADE);']
    for subject in subjects:
        assert len(subject['pages']) == 2 * len(subject['sections'])
        titles = ','.join(quote(subject[k]) for k in ['control', 'adaptive'])
        sql.append(f'INSERT INTO course_upgrade_v10_original_pages SELECT p.id,p.content,p.position,p.updated_at FROM course_pages p JOIN course_sections s ON s.id=p.section_id JOIN courses c ON c.id=s.course_id WHERE c.title IN ({titles});')
        for page in subject['pages']:
            material = (SOURCE / page['material']).read_text().strip()
            assert 'Самопроверка' in material and len(material) > 1000
            for image in re.findall(r'!\[[^\]]*\]\((/images/[^)]+)\)', material):
                assert (ROOT / 'frontend/public' / image.lstrip('/')).is_file(), image
            sql.append(f"INSERT INTO learning_skills(code,title,description) VALUES({quote(page['code'])},{quote(page['title'])},{quote(page['description'])});")
            sql.append(f"UPDATE course_pages p SET content=coalesce(p.content,'') || E'\\n\\n---\\n\\n' || {quote(material)},updated_at=now() FROM course_sections s JOIN courses c ON c.id=s.course_id WHERE p.section_id=s.id AND c.title IN ({titles}) AND p.type='theory' AND p.title={quote(page['title'])};")
            sql.append(f"INSERT INTO page_learning_skills(page_id,skill_code) SELECT p.id,{quote(page['code'])} FROM course_pages p JOIN course_sections s ON s.id=p.section_id JOIN courses c ON c.id=s.course_id WHERE c.title IN ({titles}) AND p.type='theory' AND p.title={quote(page['title'])};")
        for page in subject['pages']:
            for dep in page['prerequisites']:
                sql.append(f"INSERT INTO learning_skill_prerequisites VALUES({quote(page['code'])},{quote(dep)});")
        for index, section in enumerate(subject['sections']):
            questions = [q for p in subject['pages'][index*2:index*2+2] for q in p['questions']]
            assert len(questions) == 6
            # Correct answers do not always occupy the first position in student-facing tests.
            rotated = []
            for qi, q in enumerate(questions):
                assert len(q['options']) == 4 and len(set(q['options'])) == 4
                assert 0 <= q['correct_index'] < 4 and q['question']
                shift = int(hashlib.sha256((subject['key'] + ':' + str(index) + ':' + str(qi)).encode()).hexdigest()[:8], 16) % 4
                options = q['options'][shift:] + q['options'][:shift]
                rotated.append(dict(question=q['question'],options=options,correct_index=(q['correct_index']-shift)%4,position=qi))
            sql.append(f'''DO $upgrade$
DECLARE section_id_value BIGINT; target_position INTEGER; page_id_value BIGINT; test_id_value BIGINT; question_id_value BIGINT; item RECORD; q JSONB;
BEGIN
 FOR section_id_value IN SELECT s.id FROM course_sections s JOIN courses c ON c.id=s.course_id WHERE c.title={quote(subject['control'])} AND s.title={quote(section)} LOOP
  SELECT p.position+1 INTO target_position FROM course_pages p WHERE p.section_id=section_id_value AND p.type='test' AND NOT EXISTS(SELECT 1 FROM tests t JOIN assessment_definitions d ON d.test_id=t.id WHERE t.page_id=p.id) ORDER BY p.position DESC LIMIT 1;
  IF target_position IS NULL THEN RAISE EXCEPTION 'Missing ordinary section check'; END IF;
  -- Move later pages in descending order to respect the immediate unique position constraint.
  FOR item IN SELECT id,position FROM course_pages WHERE section_id=section_id_value AND position>=target_position ORDER BY position DESC LOOP
   UPDATE course_pages SET position=item.position+1 WHERE id=item.id;
  END LOOP;
  INSERT INTO course_pages(section_id,title,type,content,position) VALUES(section_id_value,{quote('Самостоятельная практика: '+section)},'test',NULL,target_position) RETURNING id INTO page_id_value;
  INSERT INTO course_upgrade_v10_added_pages VALUES(page_id_value);
  INSERT INTO tests(page_id,passing_score) VALUES(page_id_value,60) RETURNING id INTO test_id_value;
  FOR q IN SELECT value FROM jsonb_array_elements({quote(json.dumps(rotated,ensure_ascii=False))}::jsonb) LOOP
   INSERT INTO test_questions(test_id,question,position) VALUES(test_id_value,q->>'question',(q->>'position')::integer) RETURNING id INTO question_id_value;
   INSERT INTO test_answers(question_id,text,is_correct,position)
   SELECT question_id_value,value,(ordinality-1)=(q->>'correct_index')::integer,ordinality-1 FROM jsonb_array_elements_text(q->'options') WITH ORDINALITY;
  END LOOP;
 END LOOP;
END $upgrade$;''')
    sql.append('COMMIT;')
    return '\n\n'.join(sql) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sql = compile_catalog()
    codes = [page['code'] for subject in json.loads((SOURCE / 'catalog.json').read_text())['subjects'] for page in subject['pages']]
    down = '''-- Generated by scripts/build_course_catalog.py.
BEGIN;
-- Removes only v10 practice and its dependent progress; original learning history is retained.
DELETE FROM course_pages WHERE id IN(SELECT page_id FROM course_upgrade_v10_added_pages);
UPDATE course_pages p SET content=b.content,position=b.position,updated_at=b.updated_at
FROM course_upgrade_v10_original_pages b WHERE p.id=b.page_id;
DELETE FROM learning_skills WHERE code IN (''' + ','.join(quote(code) for code in codes) + ''');
DROP TABLE course_upgrade_v10_added_pages;
DROP TABLE course_upgrade_v10_original_pages;
COMMIT;
'''
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != sql or not DOWN_TARGET.exists() or DOWN_TARGET.read_text() != down:
            raise SystemExit('Course migration is stale; run python3 scripts/build_course_catalog.py')
        print('PASS course catalog: skill graph, practice options, local images, generated migration')
    else:
        TARGET.write_text(sql)
        DOWN_TARGET.write_text(down)
        print('Generated', TARGET.relative_to(ROOT))


if __name__ == '__main__':
    main()
