## Сначала простое условие, затем более конкретное

Условия проверяются по порядку. Если первая ветка подходит, последующие ветки этой конструкции уже не проверяются. Поэтому порядок важен: сначала размещайте специальные случаи, а затем более общие.

    points = int(input("Баллы: "))

    if points >= 90:
        print("Отлично")
    elif points >= 70:
        print("Хорошо")
    elif points >= 50:
        print("Зачёт")
    else:
        print("Нужно повторить материал")

В этом примере значения 90 и выше попадают в первую ветку, а значение 70 — во вторую. Границы диапазонов должны быть согласованы, чтобы не возникало неожиданных результатов.

