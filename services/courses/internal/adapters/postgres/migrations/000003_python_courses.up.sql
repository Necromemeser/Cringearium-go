## Аргументы и результат

Параметры позволяют передавать функции разные данные. Благодаря этому одну и ту же функцию можно вызывать для многих значений, не копируя её тело.

    def rectangle_area(width, height):
        return width * height

    first_area = rectangle_area(3, 4)
    second_area = rectangle_area(5, 2)
    print(first_area, second_area)

Функция не обязана выводить результат самостоятельно. Возвращаемое значение можно сохранить, сравнить с другим значением или передать в следующую функцию. Если функция только вызывает print(), это не означает, что она возвращает напечатанный текст.

