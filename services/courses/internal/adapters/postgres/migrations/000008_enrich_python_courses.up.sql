## Выбираем подходящий цикл

Используйте for, когда нужно пройти по диапазону или коллекции элементов. Используйте while, когда число повторений заранее неизвестно и выполнение зависит от условия. В обоих случаях заранее подумайте, когда цикл остановится.

    total = 0
    for number in range(1, 6):
        total += number
    print(total)

Переменная total накапливает сумму. Оператор += добавляет новое значение к уже сохранённому. Цикл range(1, 6) перебирает числа от 1 до 5, потому что правая граница не включается.

